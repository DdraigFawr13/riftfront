/**
 * Runs AI-vs-AI batches (Ironbound as deck A vs Verdant as deck B) in both Commander damage
 * presets and prints a Markdown report against the D-008 targets.
 * Usage: npm run sim -- [gamesPerPreset=400] [seedStart=1] [secondPlayerRound1Bonus]
 */
import { CARDS, DECKS } from "../src/content/factions.ts";
import type { CommanderDamageMode } from "../src/engine/index.ts";
import { runBatch, summarize, targetChecks, type Summary } from "../src/sim/harness.ts";

const games = Number(process.argv[2] ?? 400);
const seedStart = Number(process.argv[3] ?? 1);
const bonusArg = process.argv[4];
const extra = bonusArg === undefined ? {} : { secondPlayerRound1Bonus: Number(bonusArg) };
const modes: CommanderDamageMode[] = ["territorial_breach", "unblocked_lane"];
const pct = (x: number) => `${Math.round(x * 100)}%`;
// 95% margin for a proportion near 50%: 1.96 * sqrt(0.25 / n).
const margin = (n: number) => `±${Math.round(196 * Math.sqrt(0.25 / n))}%`;

const summaries: Summary[] = [];
const started = performance.now();
for (const mode of modes) {
  const results = runBatch({
    games,
    seedStart,
    cards: CARDS,
    decks: { A: DECKS.ironbound, B: DECKS.verdant },
    config: { commanderDamageMode: mode, ...extra },
  });
  summaries.push(summarize(mode, results));
}
const seconds = ((performance.now() - started) / 1000).toFixed(0);

const out: string[] = [];
out.push(
  `Generated by \`npm run sim -- ${process.argv.slice(2).join(" ")}\` (${games} games per preset, seeds ${seedStart}–${seedStart + games - 1}, ${seconds} s${bonusArg === undefined ? "" : `, round 1 bonus ${bonusArg}`}).`,
);
out.push("");
out.push(
  "Ironbound (deck A) plays Verdant (deck B); both sides use the rule-based AI, and seats swap every game. Percentages are measured; with this many games a rate near 50% is accurate to about " +
    margin(games) +
    " (95%).",
);
out.push("");
out.push("## Targets (D-008)");
out.push("");
out.push("| Check | " + modes.join(" | ") + " |");
out.push("| --- | " + modes.map(() => "---").join(" | ") + " |");
const checks = summaries.map(targetChecks);
checks[0]!.forEach((c, i) => {
  out.push(
    `| ${c.name} | ${checks.map((cs) => `${cs[i]!.value} ${cs[i]!.ok ? "✅" : "❌"}`).join(" | ")} |`,
  );
});
out.push("");
out.push("## Details");
for (const s of summaries) {
  out.push("");
  out.push(`### ${s.mode}`);
  out.push("");
  out.push(`- Rounds: median ${s.medianRounds}, mean ${s.meanRounds.toFixed(1)}`);
  out.push(
    `- How games ended: combat ${pct(s.combatEndRate)}, deck-out ${pct(s.deckoutEndRate)}, round cap ${pct(s.roundCapRate)}; draws ${pct(s.drawRate)}`,
  );
  out.push(
    `- First player wins ${pct(s.firstPlayerWinRate)} of decisive games; Ironbound wins ${pct(s.deckAWinRate)}, Verdant ${pct(1 - s.deckAWinRate)} (decisive games)`,
  );
  out.push(
    `- Commander damage by source: ${Object.entries(s.damageShare)
      .map(([k, v]) => `${k} ${pct(v)}`)
      .join(", ")}`,
  );
  const hist = Object.entries(s.roundsHistogram)
    .map(([r, c]) => `${r}: ${c}`)
    .join(", ");
  out.push(`- Games by final round: ${hist}`);
}
console.log("# Harness report\n");
console.log(out.join("\n"));
